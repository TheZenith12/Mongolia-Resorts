async function run() {
  const client = new MongoClient(URI);
  await client.connect();
  console.log('✅ MongoDB-д холбогдлоо');

  const col = client.db('mng-resorts').collection('places');
  const before = await col.countDocuments({});
  console.log(`📊 Одоо байгаа газар: ${before}\n`);

  let added = 0, skipped = 0;
  for (const p of PLACES) {
    const exists = await col.findOne({ name: p.name });
    if (exists) { process.stdout.write('.'); skipped++; }
    else {
      await col.insertOne({ ...p, like_count: 0, created_at: new Date(), updated_at: new Date() });
      process.stdout.write('+'); added++;
    }
  }

  console.log(`\n\n🎉 ${added} шинэ газар нэмэгдлээ (${skipped} давхцсан)\n`);

  const total = await col.countDocuments({});
  const byProvince = await col.aggregate([
    { $group: { _id: '$province', count: { $sum: 1 } } },
    { $sort: { count: -1 } },
  ]).toArray();

  console.log(`📍 Аймаг бүрээр:`);
  byProvince.forEach(b => console.log(`  ${b._id}: ${b.count}`));

  const nature  = await col.countDocuments({ type: 'nature' });
  const resorts = await col.countDocuments({ type: 'resort' });
  console.log(`\n🌿 Байгалийн газар: ${nature}`);
  console.log(`🏕️  Амралтын газар: ${resorts}`);
  console.log(`📊 НИЙТ: ${total} газар`);

  await client.close();
  console.log('\n🔌 Дууслаа');
}

run().catch(e => { console.error(e); process.exit(1); });
